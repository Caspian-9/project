def main() -> None:
    with open(IDX_PATH, encoding="utf-8") as f:
        idx = json.load(f)

    updated = 0
    for report in idx["reports"]:
        if report["id"] in UPDATES:
            report["abstract"] = UPDATES[report["id"]]
            report["abstract_source"] = "PDF第一页提取"
            updated += 1

    with open(IDX_PATH, "w", encoding="utf-8") as f:
        json.dump(idx, f, ensure_ascii=False, indent=2)

    total_real = sum(1 for r in idx["reports"] if r.get("abstract_source"))
    print(f"本次更新: {updated} 篇")
    print(f"累计精读摘要: {total_real} / {idx['metadata']['total_reports']}")


if __name__ == "__main__":
    main()
